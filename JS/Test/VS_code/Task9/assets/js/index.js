
function square(number) {
    return number * number;
}

console.log(square(5));

//Function Expression

const squareExpression = function(number) {
    return number * number;
};

console.log(squareExpression(5));

// Arrow Function


const squareArrow = (number) => {
    return number * number;
};

console.log(squareArrow(5));